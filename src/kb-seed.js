/** يزرع المقالات مرة واحدة — لا يستبدل ما عدّلته */
export function seedArticles() {
  let added = 0;
  for (const a of [...STARTER_ARTICLES, ...WEB_ARTICLES]) {
    if (get('SELECT id FROM kb_articles WHERE slug = ?', a.slug)) continue;
    kb.saveArticle(a);
    added++;
  }
  return added;
}
