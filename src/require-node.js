// حارس النسخة — يجب أن يُستورَد **قبل** أي وحدة تستورد ‎node:sqlite‎.
//
// الوحدة ‎node:sqlite‎ ظهرت في ‎22.5.0‎ لكنها ظلّت تحتاج راية
// ‎--experimental-sqlite‎ حتى ‎22.13.0‎. ومديرو التطبيقات المُدارون (hPanel،
// Passenger) هم من يشغّلون Node لا أنت، فلا مكان تمرّر فيه راية: نسخةٌ بين
// ‎22.5‎ و‎22.12‎ تبدو مطابقة للشرط وهي لا تقلع.
//
// وبلا هذا الحارس يكون العَرَض صفحةً بيضاء أو 503، ورسالةً في سجلّ لا يقرأه
// أحد نصّها ‎Cannot find module 'node:sqlite'‎ — وهي رسالة تدفع صاحبها إلى
// ‎npm install sqlite‎، وهو طريق مسدود لأن الوحدة مدمجة في Node لا في npm.
//
// ولماذا ملفّ مستقلّ: في ESM تُقيَّم الاستيرادات قبل جسم الوحدة، فلو كان
// الفحص في جسم ملفٍّ يستورد ‎node:sqlite‎ لانفجر الاستيراد قبل أن يعمل الفحص.
// الاستيرادات تُقيَّم بترتيبها، فوضعُه أوّلَ سطر في نقطة الدخول يضمن سبقه.
const MIN = [22, 13, 0];
const cur = process.versions.node.split('.').map(Number);

const older =
  cur[0] < MIN[0] || (cur[0] === MIN[0] && cur[1] < MIN[1]);

if (older) {
  console.error(`
  ✖ نسخة Node غير كافية: ${process.versions.node}

  النظام يحتاج Node 22.13.0 فأحدث — والأأمن أن تختار 24.

  السبب: كل البيانات في ‎node:sqlite‎، وهي وحدة **مدمجة في Node نفسه**.
  لا تُنصَّب بـ npm، ولا بديل لها. قبل ‎22.13‎ كانت تحتاج راية على سطر
  الأوامر، ومدير التطبيقات لا يمرّر رايات.

  الحل: غيّر نسخة Node من لوحة الاستضافة (hPanel → Node.js version → 24)
  ثم أعد تشغيل التطبيق. ثم شغّل ‎node doctor.cjs‎ للتأكد.
`);
  process.exit(1);
}
