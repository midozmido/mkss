/** قسم قابل للطيّ — الأول والثاني مفتوحان لمن يقرأ بالترتيب */
function section({ n, title, why, steps = [], note = null, open = false }) {
  return `<details class="guide-sec card" ${open ? 'open' : ''} data-reveal>
  <summary>
    <span class="guide-num" aria-hidden="true">${n}</span>
    <span class="grow">${title}</span>
    <span class="guide-caret" aria-hidden="true">${icon('arrow')}</span>
  </summary>
  <div class="guide-body">
    ${why ? `<p class="guide-why">${why}</p>` : ''}
    ${steps.length ? `<ol class="guide-steps">${steps.map((s) => `<li>${s}</li>`).join('')}</ol>` : ''}
    ${note ? `<p class="guide-note">${icon('alert')} <span>${note}</span></p>` : ''}
  </div>
</details>`;
}

const glance = (items) => `<section class="card guide-glance" data-reveal>
  <h2>${icon('sparkle')} لمحة سريعة</h2>
  <ul>${items.map((x) => `<li>${icon('check')} <span>${x}</span></li>`).join('')}</ul>
</section>`;

